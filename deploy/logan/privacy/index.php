  <h2 id="p2">2. 보유기간</h2>
  <p>개인정보는 처리 목적을 이루면 지체 없이 파기합니다. 다만 다음 정보는 관계 법령이 정한 기간 동안 보관합니다.</p>
  <ul>
    <li>계약 또는 청약철회, 대금결제 및 재화 등의 공급에 관한 기록: 5년(「전자상거래 등에서의 소비자보호에 관한 법률」)</li>
    <li>소비자의 불만 또는 분쟁처리에 관한 기록: 3년(같은 법)</li>
    <li>세금계산서 등 거래 증빙: 5년(「국세기본법」·「부가가치세법」)</li>
    <li>홈페이지 방문 기록(구글 애널리틱스): Google 애널리틱스 설정의 데이터 보관 기간 동안</li>
  </ul>

  <h2 id="p3">3. 파기 절차와 방법</h2>
  <p><strong>절차</strong>: 보유기간이 지났거나 처리 목적을 이룬 개인정보는 파기 대상을 확인한 뒤 개인정보 보호책임자의 확인을 거쳐 파기합니다. 법령에 따라 계속 보관해야 하는 정보는 다른 정보와 분리해 보관합니다.</p>
  <p><strong>방법</strong>: 전자 파일은 복구할 수 없는 방법으로 삭제하고, 카카오톡 채널 대화와 휴대전화에 저장된 사진은 삭제합니다. 종이 문서는 분쇄하거나 소각합니다.</p>

